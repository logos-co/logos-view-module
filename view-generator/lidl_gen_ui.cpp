// UI-backend glue generation (see lidl_gen_ui.h).
//
// The authoring split for type=ui_qml + interface=universal:
//
//   USER-WRITTEN   the .rep (the view contract — full QtRO power: SLOTs,
//                  PROPs, SIGNALs) and the *Backend.{h,cpp} class deriving
//                  the repc <RepClass>SimpleSource + LogosUiPluginContext
//                  (which supplies onContextReady() and the modules() typed
//                  accessors to declared dependencies — a UI plugin is a view,
//                  not a module, so it gets nothing else: no modulePath/
//                  instanceId/persistence, no events of its own). The deps'
//                  wrappers are Qt-typed (api-style qt), matching the .rep slots.
//
//   GENERATED      <name>_ui_interface.h (the *Interface: PluginInterface +
//                  IID) and <name>_ui_glue.{h,cpp} (the *Plugin:
//                  Q_PLUGIN_METADATA, name()/version(),
//                  ViewPluginBase, and the Q_INVOKABLE initLogos that
//                  constructs LogosModules, wires it into the backend —
//                  firing onContextReady — and registers the backend as the
//                  QtRO source).
//
// Existing LogosAPI*-based UI plugins (interface: legacy) are untouched.

#include "lidl_gen_ui.h"

#include <QFile>
#include <QRegularExpression>
#include <QTextStream>

bool lidlUiParseRepClass(const QString& repPath, QString* repClass, QString* whyNot)
{
    QFile f(repPath);
    if (!f.open(QIODevice::ReadOnly | QIODevice::Text)) {
        if (whyNot) *whyNot = "cannot read .rep file: " + repPath;
        return false;
    }
    const QString text = QString::fromUtf8(f.readAll());
    // Same extraction logos_module(REP_FILE ...) performs: the first class
    // declaration names the QtRO types (SimpleSource/Replica/ViewPluginBase).
    QRegularExpressionMatch m =
        QRegularExpression(QStringLiteral("class[ \\t]+([A-Za-z_][A-Za-z0-9_]*)")).match(text);
    if (!m.hasMatch()) {
        if (whyNot) *whyNot = "no `class <Name>` declaration found in " + repPath;
        return false;
    }
    if (repClass) *repClass = m.captured(1);
    return true;
}

QString lidlMakeUiInterfaceHeader(const UiGlueSpec& spec)
{
    QString h;
    QTextStream s(&h);
    s << "// AUTO-GENERATED by logos-view-generator --backend ui -- do not edit\n";
    s << "#pragma once\n\n";
    s << "#include \"interface.h\"\n\n";
    s << "class " << spec.pluginBase << "Interface : public PluginInterface\n{\npublic:\n";
    s << "    virtual ~" << spec.pluginBase << "Interface() = default;\n};\n\n";
    s << "#define " << spec.pluginBase << "Interface_iid \"org.logos." << spec.pluginBase << "Interface\"\n";
    s << "Q_DECLARE_INTERFACE(" << spec.pluginBase << "Interface, " << spec.pluginBase << "Interface_iid)\n";
    return h;
}

QString lidlMakeUiGlueHeader(const UiGlueSpec& spec)
{
    QString h;
    QTextStream s(&h);
    s << "// AUTO-GENERATED by logos-view-generator --backend ui -- do not edit\n";
    s << "#pragma once\n\n";
    s << "#include <QObject>\n#include <QString>\n#include <memory>\n\n";
    s << "#include \"" << spec.backendHeader << "\"\n";
    s << "#include \"" << spec.moduleName << "_ui_interface.h\"\n";
    s << "#include \"LogosViewPluginBase.h\"\n\n";
    s << "class LogosAPI;\nstruct LogosModules;\n\n";
    s << "// Generated UI plugin around the user-written " << spec.backendClass << ".\n";
    s << "// Owns the backend, wires the LogosModules typed-deps aggregate into it\n";
    s << "// on initLogos (firing onContextReady — so dependency subscriptions are\n";
    s << "// live before the view's first call), and registers it as the QtRO\n";
    s << "// source for the QML replica.\n";
    s << "class " << spec.pluginBase << "Plugin : public QObject,\n";
    s << QString(" ").repeated(22 + spec.pluginBase.size()) << "public " << spec.pluginBase << "Interface,\n";
    s << QString(" ").repeated(22 + spec.pluginBase.size()) << "public " << spec.repClass << "ViewPluginBase\n{\n";
    s << "    Q_OBJECT\n";
    s << "    Q_PLUGIN_METADATA(IID " << spec.pluginBase << "Interface_iid FILE \"metadata.json\")\n";
    s << "    Q_INTERFACES(" << spec.pluginBase << "Interface LogosViewPlugin)\n\npublic:\n";
    s << "    // Ctor/dtor are out-of-line: this header is compiled by moc TUs\n";
    s << "    // where LogosModules may be incomplete.\n";
    s << "    explicit " << spec.pluginBase << "Plugin(QObject* parent = nullptr);\n";
    s << "    ~" << spec.pluginBase << "Plugin() override;\n\n";
    s << "    QString name() const override { return QStringLiteral(\"" << spec.moduleName << "\"); }\n";
    s << "    QString version() const override { return QStringLiteral(\"" << spec.moduleVersion << "\"); }\n\n";
    s << "    Q_INVOKABLE void initLogos(LogosAPI* api);\n\n";
    // Teardown, reached by the host through the META-OBJECT rather than the
    // vtable. PluginInterface is compiled separately into every plugin, so
    // adding a virtual there would shift the vtable under every plugin already
    // built and turn a missing hook into undefined behaviour instead of a
    // no-op. `initLogos` above is delivered by name for the same reason.
    //
    // Emitted unconditionally, for EVERY view. A backend that does not derive
    // LogosUiPluginContext answers Synchronous through the SFINAE helper, so
    // the surface costs a view that ignores it exactly one meta-call at
    // teardown -- and emitting it always is what lets ui-host resolve one name
    // rather than probing for two shapes.
    //
    // Returns the LogosShutdown as an int because the host resolves this by
    // signature string and must not need the SDK enum to do it.
    s << "    Q_INVOKABLE int aboutToUnload();\n\n";
    s << "Q_SIGNALS:\n";
    s << "    // Emitted when an Asynchronous teardown has finished. The host\n";
    s << "    // connects to this by name and stops waiting on the first one.\n";
    s << "    void unloadFinished();\n\n";
    s << "private:\n";
    // Destroyed in reverse: the backend first, while the dependency wrappers
    // its destructor may still call are alive.
    s << "    std::unique_ptr<LogosModules> m_logosModules;\n";
    s << "    std::unique_ptr<" << spec.backendClass << "> m_backend;\n";
    s << "};\n";
    return h;
}

QString lidlMakeUiGlueSource(const UiGlueSpec& spec)
{
    QString c;
    QTextStream s(&c);
    s << "// AUTO-GENERATED by logos-view-generator --backend ui -- do not edit\n";
    s << "#include \"" << spec.moduleName << "_ui_glue.h\"\n\n";
    s << "#include \"logos_api.h\"\n";
    s << "#include \"logos_ui_plugin_context.h\"\n";
    s << "#include \"logos_sdk.h\"\n\n";
    s << spec.pluginBase << "Plugin::" << spec.pluginBase << "Plugin(QObject* parent)\n";
    s << "    : QObject(parent)\n";
    s << "    , m_backend(std::make_unique<" << spec.backendClass << ">())\n";
    s << "{\n}\n\n";
    s << spec.pluginBase << "Plugin::~" << spec.pluginBase << "Plugin() = default;\n\n";
    s << "void " << spec.pluginBase << "Plugin::initLogos(LogosAPI* api)\n{\n";
    s << "    if (m_logosModules || !api) return;\n";
    s << "    // Construct the typed-deps aggregate and wire it into the backend.\n";
    s << "    // maybeSetUiPluginModules fires onContextReady once modules() is live,\n";
    s << "    // so the backend can make typed calls and subscribe to dependency\n";
    s << "    // events from the hook. A UI plugin is a view, not a module — it has\n";
    s << "    // no host identity (modulePath/instanceId/persistence) to wire. The\n";
    s << "    // SFINAE helper no-ops if the backend doesn't derive LogosUiPluginContext.\n";
    s << "    m_logosModules = std::make_unique<LogosModules>(api);\n";
    s << "    _logos_codegen_::maybeSetUiPluginModules(*m_backend, m_logosModules.get());\n";
    s << "    // Register the backend (a " << spec.repClass << "SimpleSource) as the QtRO\n";
    s << "    // source so ui-host can enableRemoting the typed " << spec.repClass << "SourceAPI.\n";
    s << "    setBackend(m_backend.get());\n";
    s << "}\n\n";
    // Teardown. The plugin object is what the host reaches by name; the work
    // itself belongs to the user-written backend.
    s << "int " << spec.pluginBase << "Plugin::aboutToUnload()\n{\n";
    s << "    // maybeUiPluginAboutToUnload installs the completion trampoline\n";
    s << "    // BEFORE asking the backend, because a backend that finishes inline\n";
    s << "    // would otherwise signal into an empty slot and the host would wait\n";
    s << "    // out the whole grace period for a view already done.\n";
    s << "    //\n";
    s << "    // The trampoline runs on whichever thread the backend finished on, so\n";
    s << "    // it must not touch the plugin directly -- a QUEUED invokeMethod\n";
    s << "    // marshals the emission back to the plugin's thread, which is where\n";
    s << "    // the host is waiting. It answers 0 (Synchronous) for a backend that\n";
    s << "    // does not derive LogosUiPluginContext.\n";
    s << "    return _logos_codegen_::maybeUiPluginAboutToUnload(*m_backend, [this]() {\n";
    s << "        QMetaObject::invokeMethod(this, \"unloadFinished\", Qt::QueuedConnection);\n";
    s << "    });\n";
    s << "}\n";
    return c;
}

// ── --backend ui-module ─────────────────────────────────────────────────────
//
// The same user-written .rep and Backend, run as a CORE MODULE: loaded by
// logos core like any module, with the module context every module gets, and
// reached by its view over a private, authenticated QtRO channel the module
// publishes itself (LogosViewChannel) instead of through ui-host.
//
// The plugin hands logos core a dedicated provider (LogosProviderPlugin), so
// the module's callable API is exactly view_endpoint() — not every slot the
// plugin QObject happens to have (deleteLater, initLogos, ...), which is what
// wrapping the plugin itself would expose. An app that provides intents adds
// deliver() (intents_module's contracts/intent_provider.lidl), for
// intents_module alone, forwarded to the backend's own deliver().

QString lidlMakeUiModuleGlueHeader(const UiGlueSpec& spec)
{
    QString h;
    QTextStream s(&h);
    s << "// AUTO-GENERATED by logos-view-generator --backend ui-module -- do not edit\n";
    s << "#pragma once\n\n";
    s << "#include <QObject>\n#include <QString>\n#include <memory>\n\n";
    s << "#include \"interface.h\"\n";
    s << "#include \"logos_provider_interface.h\"\n\n";
    s << "class LogosAPI;\nstruct LogosModules;\nclass LogosViewChannel;\nclass " << spec.backendClass << ";\n\n";
    s << "// Core-module plugin around the user-written " << spec.backendClass << ".\n";
    s << "// Owns the backend and its view channel; logos core reaches the module\n";
    s << "// through the provider it creates, whose only method is view_endpoint().\n";
    s << "class " << spec.pluginBase << "Plugin : public QObject, public PluginInterface,\n";
    s << QString(" ").repeated(14 + spec.pluginBase.size()) << "public LogosProviderPlugin\n{\n";
    s << "    Q_OBJECT\n";
    s << "    Q_PLUGIN_METADATA(IID PluginInterface_iid FILE \"metadata.json\")\n";
    s << "    Q_INTERFACES(PluginInterface LogosProviderPlugin)\n\npublic:\n";
    s << "    explicit " << spec.pluginBase << "Plugin(QObject* parent = nullptr);\n";
    s << "    ~" << spec.pluginBase << "Plugin() override;\n\n";
    s << "    QString name() const override { return QStringLiteral(\"" << spec.moduleName << "\"); }\n";
    s << "    QString version() const override { return QStringLiteral(\"" << spec.moduleVersion << "\"); }\n\n";
    s << "    LogosProviderObject* createProviderObject() override;\n\n";
    s << "    // Called by the provider once logos core hands it its LogosAPI.\n";
    s << "    void setUp(LogosAPI* api);\n";
    s << "    QString viewEndpoint();\n";
    if (spec.intentProvider) {
        s << "    // intents_module's delivery: the backend's deliver(), for intents_module alone.\n";
        s << "    QString deliver(const QString& dispatch, const QString& intent,\n";
        s << "                    const QString& paramsJson, const QString& requester);\n";
    }
    s << "\n";
    s << "    // The module teardown hook logos_host reaches BY NAME on the plugin\n";
    s << "    // (0 = Synchronous, 1 = Asynchronous; see logos_plugin_unload.h).\n";
    s << "    Q_INVOKABLE int aboutToUnload();\n\n";
    s << "Q_SIGNALS:\n";
    s << "    void unloadFinished();\n\n";
    s << "private:\n";
    // Destroyed in reverse: the channel first, then the backend, while the
    // dependency wrappers its destructor may still call are alive.
    s << "    std::unique_ptr<LogosModules> m_logosModules;\n";
    s << "    std::unique_ptr<" << spec.backendClass << "> m_backend;\n";
    s << "    std::unique_ptr<LogosViewChannel> m_channel;\n";
    s << "};\n";
    return h;
}

QString lidlMakeUiModuleGlueSource(const UiGlueSpec& spec)
{
    const QString plugin = spec.pluginBase + QStringLiteral("Plugin");
    const QString provider = spec.pluginBase + QStringLiteral("Provider");
    QString c;
    QTextStream s(&c);
    s << "// AUTO-GENERATED by logos-view-generator --backend ui-module -- do not edit\n";
    s << "#include \"" << spec.moduleName << "_ui_module_glue.h\"\n\n";
    s << "#include <QJsonArray>\n#include <QJsonObject>\n#include <QVariantMap>\n\n";
    s << "#include \"" << spec.backendHeader << "\"\n";
    s << "#include \"logos_api.h\"\n";
    s << "#include \"logos_module_context.h\"\n";
    s << "#include \"logos_provider_object.h\"\n";
    s << "#include \"logos_view_channel.h\"\n";
    s << "#include \"logos_sdk.h\"\n";
    if (spec.intentProvider) {
        s << "#include \"logos_caller.h\"\n\n";
        s << "#include <type_traits>\n#include <utility>\n";
    }
    s << "\n";
    s << "namespace {\n\n";
    if (spec.intentProvider) {
        s << "template <typename B, typename = void>\n";
        s << "struct HasDeliver : std::false_type {};\n";
        s << "template <typename B>\n";
        s << "struct HasDeliver<B, std::void_t<decltype(QString(std::declval<B&>().deliver(\n";
        s << "    QString(), QString(), QString(), QString())))>> : std::true_type {};\n\n";
        // Not an error: an app can move its backend to a core module first and
        // its intents later. Until it has deliver(), every delivery is refused.
        const QString missing = spec.viewName + QStringLiteral(" provides intents (metadata.json `provides`), but ")
            + spec.backendClass + QStringLiteral(" has no QString deliver(const QString& dispatch, "
              "const QString& intent, const QString& paramsJson, const QString& requester): "
              "intents_module's deliveries are refused");
        // A template, so the warning comes only with the backend that lacks it.
        s << "template <typename B>\n";
        s << "[[deprecated(\"" << missing << "\")]] void backendHasNoDeliver() {}\n\n";
        s << "template <typename B>\n";
        s << "QString deliverTo(B& backend, const QString& dispatch, const QString& intent,\n";
        s << "                  const QString& paramsJson, const QString& requester)\n{\n";
        s << "    if constexpr (HasDeliver<B>::value) {\n";
        s << "        return backend.deliver(dispatch, intent, paramsJson, requester);\n";
        s << "    } else {\n";
        s << "        backendHasNoDeliver<B>();\n";
        s << "        static bool warned = false;\n";
        s << "        if (!warned) {\n";
        s << "            warned = true;\n";
        s << "            qWarning(\"%s\", \"" << missing << "\");\n";
        s << "        }\n";
        s << "        (void)backend; (void)dispatch; (void)intent; (void)paramsJson; (void)requester;\n";
        s << "        return QStringLiteral(\"{\\\"ok\\\":false}\");\n";
        s << "    }\n";
        s << "}\n\n";
        s << "// Who is calling, for one dispatch: pulled from the host image and pushed\n";
        s << "// where logos::currentCaller() reads it in this one, as module glue does.\n";
        s << "struct CallerPush {\n";
        s << "    explicit CallerPush(const std::string& caller) { logos::detail::setCallCaller(caller.c_str()); }\n";
        s << "    ~CallerPush() { logos::detail::setCallCaller(nullptr); }\n";
        s << "};\n\n";
    }
    s << (spec.intentProvider
          ? "// The module's callable surface: view_endpoint() and deliver(), nothing else.\n"
          : "// The module's callable surface: view_endpoint() and nothing else.\n");
    s << "class " << provider << " : public LogosProviderBase\n{\npublic:\n";
    s << "    explicit " << provider << "(" << plugin << "* plugin) : m_plugin(plugin) {}\n\n";
    s << "    QString providerName() const override { return m_plugin->name(); }\n";
    s << "    QString providerVersion() const override { return m_plugin->version(); }\n\n";
    s << "    QVariant callMethod(const QString& method, const QVariantList& args) override\n    {\n";
    s << "        if (method == QLatin1String(\"view_endpoint\") && args.isEmpty())\n";
    s << "            return m_plugin->viewEndpoint();\n";
    if (spec.intentProvider) {
        s << "        if (method == QLatin1String(\"deliver\") && args.size() == 4) {\n";
        s << "            const CallerPush caller(currentCallerJson());\n";
        s << "            return m_plugin->deliver(args[0].toString(), args[1].toString(),\n";
        s << "                                     args[2].toString(), args[3].toString());\n";
        s << "        }\n";
    }
    s << "        return QVariantMap{ { QStringLiteral(\"code\"), QStringLiteral(\"unknown_method\") },\n";
    s << "                            { QStringLiteral(\"message\"), QStringLiteral(\"unknown method '%1'\").arg(method) },\n";
    s << "                            { QStringLiteral(\"origin\"), providerName() } };\n";
    s << "    }\n\n";
    s << "    QJsonArray getMethods() override\n    {\n";
    s << "        QJsonArray methods{ QJsonObject{ { QStringLiteral(\"name\"), QStringLiteral(\"view_endpoint\") },\n";
    s << "                                         { QStringLiteral(\"signature\"), QStringLiteral(\"view_endpoint()\") },\n";
    s << "                                         { QStringLiteral(\"returnType\"), QStringLiteral(\"QString\") },\n";
    s << "                                         { QStringLiteral(\"isInvokable\"), true },\n";
    s << "                                         { QStringLiteral(\"parameters\"), QJsonArray() },\n";
    s << "                                         { QStringLiteral(\"type\"), QStringLiteral(\"method\") } } };\n";
    if (spec.intentProvider) {
        s << "        QJsonArray params;\n";
        s << "        for (const char* p : { \"dispatch\", \"intent\", \"params_json\", \"requester\" })\n";
        s << "            params.append(QJsonObject{ { QStringLiteral(\"name\"), QLatin1String(p) },\n";
        s << "                                       { QStringLiteral(\"type\"), QStringLiteral(\"QString\") } });\n";
        s << "        methods.append(QJsonObject{ { QStringLiteral(\"name\"), QStringLiteral(\"deliver\") },\n";
        s << "                                    { QStringLiteral(\"signature\"), QStringLiteral(\"deliver(QString,QString,QString,QString)\") },\n";
        s << "                                    { QStringLiteral(\"returnType\"), QStringLiteral(\"QString\") },\n";
        s << "                                    { QStringLiteral(\"isInvokable\"), true },\n";
        s << "                                    { QStringLiteral(\"parameters\"), params },\n";
        s << "                                    { QStringLiteral(\"type\"), QStringLiteral(\"method\") } });\n";
    }
    s << "        return methods;\n";
    s << "    }\n\n";
    s << "protected:\n";
    s << "    void onInit(LogosAPI* api) override { m_plugin->setUp(api); }\n\n";
    s << "private:\n";
    s << "    " << plugin << "* m_plugin;\n";
    s << "};\n\n";
    s << "} // namespace\n\n";
    s << plugin << "::" << plugin << "(QObject* parent)\n";
    s << "    : QObject(parent)\n";
    s << "    , m_backend(std::make_unique<" << spec.backendClass << ">())\n";
    s << "{\n}\n\n";
    s << plugin << "::~" << plugin << "() = default;\n\n";
    s << "LogosProviderObject* " << plugin << "::createProviderObject()\n{\n";
    s << "    return new " << provider << "(this);\n";
    s << "}\n\n";
    s << "void " << plugin << "::setUp(LogosAPI* api)\n{\n";
    s << "    if (m_logosModules || !api) return;\n";
    s << "    logosAPI = api;\n";
    s << "    // The module context every core module gets, wired the way generated\n";
    s << "    // module glue wires it: dependency callers first, so onContextReady()\n";
    s << "    // can already use them; the context last, which fires it.\n";
    s << "    m_logosModules = std::make_unique<LogosModules>(api);\n";
    s << "    _logos_codegen_::maybeSetModuleName(*m_backend, name().toStdString());\n";
    s << "    _logos_codegen_::maybeSetLogosModules(*m_backend, m_logosModules.get());\n";
    s << "    _logos_codegen_::maybeSetContext(*m_backend,\n";
    s << "        api->property(\"modulePath\").toString().toStdString(),\n";
    s << "        api->property(\"instanceId\").toString().toStdString(),\n";
    s << "        api->property(\"instancePersistencePath\").toString().toStdString());\n";
    s << "    m_channel = std::make_unique<LogosViewChannel>(name(), QStringLiteral(\""
      << spec.viewName << "\"));\n";
    // Published as the SimpleSource, as ui-host does: SourceAPI<T> takes
    // &T::<property>, and a backend member of the same name would hide it.
    s << "    m_channel->publishSource<" << spec.repClass << "SourceAPI>(static_cast<"
      << spec.repClass << "SimpleSource*>(m_backend.get()), QStringLiteral(\""
      << spec.repClass << "\"));\n";
    s << "    m_channel->publishModelProperties(m_backend.get());\n";
    s << "}\n\n";
    s << "QString " << plugin << "::viewEndpoint()\n{\n";
    s << "    return m_channel ? m_channel->endpoint() : QString();\n";
    s << "}\n\n";
    if (spec.intentProvider) {
        s << "QString " << plugin << "::deliver(const QString& dispatch, const QString& intent,\n";
        s << QString(" ").repeated(int(plugin.size()) + 18) << "const QString& paramsJson, const QString& requester)\n{\n";
        s << "    // Anyone else's call reads as a delivery nobody took.\n";
        s << "    if (!logos::currentCaller().isModule(\"intents_module\"))\n";
        s << "        return QStringLiteral(\"{\\\"ok\\\":false}\");\n";
        s << "    return deliverTo(*m_backend, dispatch, intent, paramsJson, requester);\n";
        s << "}\n\n";
    }
    s << "int " << plugin << "::aboutToUnload()\n{\n";
    s << "    // Installed BEFORE asking: a backend that finishes inline would\n";
    s << "    // otherwise signal into an empty slot. Queued, because the backend may\n";
    s << "    // finish on another thread and the host waits on this one.\n";
    s << "    _logos_codegen_::maybeSetUnloadFinished(*m_backend, [this]() {\n";
    s << "        QMetaObject::invokeMethod(this, \"unloadFinished\", Qt::QueuedConnection);\n";
    s << "    });\n";
    s << "    return static_cast<int>(_logos_codegen_::maybeAboutToUnload(*m_backend));\n";
    s << "}\n";
    return c;
}
